async function findPet(application) {
  await application.firstWindow();
  for (let attempt = 0; attempt < 50; attempt += 1) {
    const pet = application.windows().find((window) => window.url().startsWith('file:') && window.url().endsWith('/renderer/index.html'));
    if (pet) return pet;
    await new Promise((resolve) => setTimeout(resolve, 100));
  }
  throw new Error('Pet window did not load');
}

